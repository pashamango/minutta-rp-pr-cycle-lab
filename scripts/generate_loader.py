#!/usr/bin/env python3
"""Generate zero-server base64-embedded JS loader for AMDE WebAssembly demo."""

import base64
import os
import sys

def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    root_dir = os.path.abspath(os.path.join(script_dir, ".."))
    wasm_path = os.path.join(root_dir, "demo", "pkg", "amde_demo_wasm.wasm")
    js_path = os.path.join(root_dir, "demo", "pkg", "amde_demo_wasm.js")

    if not os.path.exists(wasm_path):
        print(f"ERROR: {wasm_path} does not exist.")
        sys.exit(1)

    with open(wasm_path, "rb") as f:
        wasm_bytes = f.read()

    b64_wasm = base64.b64encode(wasm_bytes).decode("ascii")

    js_template = """// AMDE WebAssembly Demo Loader (Zero-server & fetch compatible)
// Auto-generated by scripts/generate_loader.py (PRD-29 / MIN-90)

(function(global) {
  const EMBEDDED_WASM_BASE64 = "__B64_PAYLOAD__";

  class AmdeWasmEngine {
    constructor() {
      this.instance = null;
      this.exports = null;
      this.ready = false;
    }

    async init() {
      if (this.ready) return this;

      let wasmBytes = null;

      // Strategy 1: Attempt standard fetch if served over HTTP/HTTPS
      if (typeof window !== "undefined" && window.location && window.location.protocol.startsWith("http")) {
        try {
          const response = await fetch("pkg/amde_demo_wasm.wasm");
          if (response.ok) {
            wasmBytes = await response.arrayBuffer();
          }
        } catch (e) {
          console.warn("[AMDE-WASM] Fetch failed, falling back to embedded base64:", e);
        }
      }

      // Strategy 2: Embedded base64 fallback (works offline and on file:// without web server)
      if (!wasmBytes) {
        const binaryString = atob(EMBEDDED_WASM_BASE64);
        const len = binaryString.length;
        const bytes = new Uint8Array(len);
        for (let i = 0; i < len; i++) {
          bytes[i] = binaryString.charCodeAt(i);
        }
        wasmBytes = bytes.buffer;
      }

      const { instance } = await WebAssembly.instantiate(wasmBytes, {});
      this.instance = instance;
      this.exports = instance.exports;
      this.ready = true;
      console.log("[AMDE-WASM] Engine initialized successfully, version:", this.exports.amde_wasm_version());
      return this;
    }

    _readJson(callFn) {
      callFn();
      const ptr = this.exports.amde_get_last_result_ptr();
      const len = this.exports.amde_get_last_result_len();
      const mem = new Uint8Array(this.exports.memory.buffer, ptr, len);
      const str = new TextDecoder("utf-8").decode(mem);
      return JSON.parse(str);
    }

    verifyClaims() {
      return this._readJson(() => this.exports.amde_verify_claims());
    }

    getGoldenBands(n = 6) {
      return this._readJson(() => this.exports.amde_get_golden_bands(n));
    }

    evalPoint(sigma, t) {
      return this._readJson(() => this.exports.amde_eval_point(sigma, t));
    }

    evalSigmaSlice(sigmaMin, sigmaMax, steps, t) {
      return this._readJson(() => this.exports.amde_eval_sigma_slice(sigmaMin, sigmaMax, steps, t));
    }

    evalTSlice(tMin, tMax, steps, sigma) {
      return this._readJson(() => this.exports.amde_eval_t_slice(tMin, tMax, steps, sigma));
    }

    geoidFactorize(n) {
      return this._readJson(() => this.exports.amde_geoid_factorize(BigInt(n)));
    }

    geoidEvolve(n, ruleId = 0) {
      return this._readJson(() => this.exports.amde_geoid_evolve(BigInt(n), ruleId));
    }

    geoidFullCycle(n, ruleId = 0, horizonK = 4) {
      return this._readJson(() => this.exports.amde_geoid_full_cycle(BigInt(n), ruleId, horizonK));
    }
  }

  global.AmdeWasmEngine = AmdeWasmEngine;
  global.amdeEngine = new AmdeWasmEngine();
})(typeof window !== "undefined" ? window : globalThis);
"""

    js_content = js_template.replace("__B64_PAYLOAD__", b64_wasm)
    with open(js_path, "w", encoding="utf-8") as f:
        f.write(js_content)

    print(f"Generated {js_path} ({len(js_content)} bytes, base64 payload embedded)")

if __name__ == "__main__":
    main()
